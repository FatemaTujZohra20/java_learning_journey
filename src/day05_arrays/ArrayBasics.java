package day05_arrays;

/**
 * Introduction to arrays
 */
public class ArrayBasics {
    public static void main(String[] args) {
        // Declaration
        int[] numbers;

        // Initialization
        numbers = new int[6];

        // Assign values
        numbers[0] = 20;
        numbers[1] = 30;

        System.out.println(numbers[0]);
        System.out.println(numbers.length);

    }
}
